"""Extended binary QR codes of lengths 48, 72, 80 (p = 47, 71, 79; p = -1 mod 8, ord_p(2) = (p-1)/2).
Generator polynomial = an irreducible factor of degree (p-1)/2 of the p-th cyclotomic polynomial over GF(2);
the code generated by it has dimension (p+1)/2, extended by an overall parity bit.  Checks self-duality and
double evenness, then writes two standard-form generator matrices for disjoint information sets.
Usage: qrgen.py P OUT"""
import sys, random
from flint import nmod_poly
p = int(sys.argv[1]); out = sys.argv[2]
fl = nmod_poly([1] * p, 2).factor()[1]                         # Phi_p = 1 + x + ... + x^(p-1) over GF(2)
degs = sorted(f.degree() for f, e in fl)
assert degs == [(p - 1) // 2] * 2, degs
g = [int(c) for c in fl[0][0].coeffs()]                        # g[i] = coeff of x^i
gm = 0
for i, c in enumerate(g):
    if int(c) % 2: gm |= 1 << i
n = p + 1; k = p - ((p - 1) // 2)
rows = []
for s in range(k):
    r = gm << s
    par = bin(r).count('1') & 1
    rows.append(r | (par << p))
pc = lambda v: bin(v).count('1')
assert all(pc(a & b) % 2 == 0 for a in rows for b in rows), "not self-orthogonal"
assert all(pc(r) % 4 == 0 for r in rows), "generator not doubly even"


def rref_on(rows, cols):
    """standard form on columns cols (list of k columns): returns rows R with R[i] having 1 at cols[i] and 0 at
    the other cols, or None if cols is not an information set"""
    R = list(rows); used = []
    for i, c in enumerate(cols):
        piv = next((j for j in range(i, len(R)) if (R[j] >> c) & 1), None)
        if piv is None: return None
        R[i], R[piv] = R[piv], R[i]
        for j in range(len(R)):
            if j != i and (R[j] >> c) & 1: R[j] ^= R[i]
    return R


cols = list(range(n)); random.seed(1)
for attempt in range(1000):
    I1, I2 = cols[:k], cols[k:]
    A = rref_on(rows, I1); B = rref_on(rows, I2)
    if A is not None and B is not None: break
    random.shuffle(cols)
else:
    sys.exit("no split found")
# rank check (A is k independent rows) and self-duality: k = n/2 and self-orthogonal
assert 2 * k == n
with open(out, 'w') as f:
    f.write(f"{n} {k}\n")
    for R in (A, B):
        for r in R: f.write(f"{r:032x}\n")
print(f"p={p}: n={n} k={k}, generator weight {pc(gm)}, self-orthogonal, doubly even, split after {attempt} shuffles")
