/* golay24.h -- own construction of the extended binary Golay code (audit code, independent of the pipelines).
   Coordinates 0..22 = Z/23, 23 = infinity. Cyclic [23,12,7] code generated by g(x) = 1+x^2+x^4+x^5+x^6+x^10+x^11,
   extended by an overall parity bit at coordinate 23. */
#ifndef GOLAY24_H
#define GOLAY24_H
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
static uint32_t GB[12];              /* basis */
static uint32_t GW[4096];            /* all codewords */
static uint32_t OCT[759], DOD[2576];
static int nOCT = 0, nDOD = 0;
static void golay_build(void) {
    const int gexp[] = { 0, 2, 4, 5, 6, 10, 11 };
    for (int i = 0; i < 12; i++) {
        uint32_t w = 0;
        for (int t = 0; t < 7; t++) w |= 1u << ((gexp[t] + i) % 23);
        if (__builtin_popcount(w) & 1) w |= 1u << 23;
        GB[i] = w;
    }
    for (int m = 0; m < 4096; m++) { uint32_t w = 0; for (int i = 0; i < 12; i++) if ((m >> i) & 1) w ^= GB[i]; GW[m] = w; }
    int hist[25] = { 0 };
    nOCT = nDOD = 0;
    for (int m = 0; m < 4096; m++) {
        int wt = __builtin_popcount(GW[m]); hist[wt]++;
        if (wt == 8) OCT[nOCT++] = GW[m];
        if (wt == 12) DOD[nDOD++] = GW[m];
    }
    if (!(hist[0] == 1 && hist[8] == 759 && hist[12] == 2576 && hist[16] == 759 && hist[24] == 1 && nOCT == 759 && nDOD == 2576)) {
        fprintf(stderr, "golay_build: wrong weight distribution\n"); exit(9);
    }
}
static int golay_member(uint32_t w) { /* via the 4096 words (sorted lookup would be faster; fine for checks) */
    for (int m = 0; m < 4096; m++) if (GW[m] == w) return 1; return 0;
}
static uint32_t perm_apply(const int *pm, uint32_t w) { uint32_t r = 0; for (uint32_t t = w; t; t &= t - 1) r |= 1u << pm[__builtin_ctz(t)]; return r; }
static int perm_is_aut(const int *pm) { for (int i = 0; i < 12; i++) if (!golay_member(perm_apply(pm, GB[i]))) return 0; return 1; }
#endif
