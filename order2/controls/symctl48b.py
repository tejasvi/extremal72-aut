"""LTS-r validation on QR48: (1) r=1 LTSR vs LTS-1 (SYMFILE) node counts identical; (2) for groups H in
{Aut(Y48), subgroups generated by random elements} and r in RLIST: run lwe7 with LTSFILE, then the H-orbit closure
(generator BFS, gauge-normalised) of the reported solutions must equal exactly the plain solution set (5760)."""
import sys, pickle, subprocess, os, random
sys.path.insert(0, '<HOME>/c72/explore/src')
from common import *
import mkinst
from qrctl import setup
from nautyaut import aut_gens
from symprep import closure, ap, coords_fn
from symprep2 import prep2
env = dict(os.environ, TMPDIR='<HOME>/c72/explore/tmp')
ENG = '<HOME>/c72/explore/src/lwe7'
S = setup(47); m = 24; d = 12
Yg = S['Ygens']
gens = aut_gens(Yg, m)
G = closure(gens, m)
print("Aut(Y48) order", len(G), flush=True)
D = pickle.load(open('<HOME>/c72/explore/inst/qr48.pkl', 'rb'))
flagname = sys.argv[1] if len(sys.argv) > 1 else 'qr'
w = D['L']['w']
if flagname == 'alt':      # a different flag: reverse the order of the low words among the first 6, keep a basis
    w = w[1:4][::-1] + [w[0]] + w[4:]
L = mkinst.build(Yg, w, m=m, d=d, verbose=False)
inst = f'<HOME>/c72/explore/inst/qr48b_{flagname}.txt'
mkinst.export(L, inst)
def run(extra):
    out = subprocess.run([ENG, inst], capture_output=True, text=True, env=dict(env, **extra)).stdout
    sols = [int(l.split()[1], 16) for l in out.split('\n') if l.startswith('SOLUTION')]
    lev = [l for l in out.split('\n') if l.startswith('LEVEL')]
    return sols, lev
plain, _ = run({})
solf = set(plain)
print(f"flag {flagname}: plain solutions {len(solf)}", flush=True)
E = L['E']; entf = L['entf']; free = L['free']; K = len(w)
eidx = {e: k for k, e in enumerate(E)}
co = coords_fn(w)
gp = {}
for q in range(m):
    g_ = 0
    for (i, j) in E:
        if ((w[i] & w[j]) >> q) & 1: g_ |= 1 << eidx[(i, j)]
    for b in sorted(gp):
        if (g_ >> b) & 1: g_ ^= gp[b]
    if g_:
        b = (g_ & -g_).bit_length() - 1
        for b2 in list(gp):
            if (gp[b2] >> b) & 1: gp[b2] ^= g_
        gp[b] = g_
def gram(a):
    Gm = [[0] * K for _ in range(K)]
    for e, (i, j) in enumerate(E):
        vm, c = entf[e]; v = (pc(vm & a) & 1) ^ c; Gm[i][j] = Gm[j][i] = v
    return Gm
def normalise(Gm):
    Gv = 0
    for e, (i, j) in enumerate(E):
        if Gm[i][j]: Gv |= 1 << e
    for b, g_ in gp.items():
        if (Gv >> b) & 1: Gv ^= g_
    a = 0
    for k, e in enumerate(free):
        if (Gv >> e) & 1: a |= 1 << k
    return a
def image(a, cw):
    Gm = gram(a); Gn = [[0] * K for _ in range(K)]
    for i in range(K):
        ci = cw[i]; rowv = [0] * K
        for p in range(K):
            if (ci >> p) & 1:
                for q in range(K): rowv[q] ^= Gm[p][q]
        for j in range(i, K):
            cj = cw[j]; v = 0
            for q in range(K):
                if (cj >> q) & 1: v ^= rowv[q]
            Gn[i][j] = Gn[j][i] = v
    return normalise(Gn)
def closure_check(sols, hgens):
    gw = [[co(ap(g, w[i], m)) for i in range(K)] for g in hgens]
    cover = set(sols); fr = list(sols); outside = 0
    while fr:
        nf = []
        for a in fr:
            for cw in gw:
                b = image(a, cw)
                if b not in cover:
                    cover.add(b); nf.append(b)
                    if b not in solf: outside += 1
        fr = nf
    return len(cover), outside, cover == solf
rng = random.Random(7)
groups = [('Aut', gens, G)]
for name, k in (('H2', 2), ('H1', 1)):
    hg = [list(rng.choice(G)) for _ in range(k)]
    H = closure(hg, m)
    groups.append((name, hg, H))
RLIST = [int(x) for x in (sys.argv[2].split(',') if len(sys.argv) > 2 else ['1', '2', '3'])]
# (1) r=1 vs LTS-1 on the full group
from symprep import prep
prep(gens, m, inst, inst + '.sym', w[0], verbose=False)
_, lev_sym = run({'SYMFILE': inst + '.sym'})
for gname, hg, H in groups:
    for r in RLIST:
        lf = inst + f'.{gname}.r{r}.ltsr'
        prep2(hg, m, inst, lf, w, r, verbose=False, G=H)
        sols, lev = run({'LTSFILE': lf})
        nc, outside, eq = closure_check(sols, hg)
        same = ''
        if gname == 'Aut' and r == 1:
            a = [x.split()[7] for x in lev_sym]; b = [x.split()[7] for x in lev]
            same = f"; node counts identical to LTS-1: {a == b}"
        print(f"group {gname} |H|={len(H)} r={r}: reps {len(sols)}, H-closure {nc}, outside {outside}, equals plain set: {eq}{same}", flush=True)
