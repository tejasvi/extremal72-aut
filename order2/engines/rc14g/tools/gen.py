"""gen.py DUMP OUT.h [LEVELS] : per-package lane loops for the narrow paths (kt 7 and 8) from an LWE11GENDUMP file.
Each generated function is the engine's loop for that level fully unrolled: lane index, translate-table row offsets
(i * 64, i * hs) and direct-table offsets (DOFF[i]) become constants.  gen_check() verifies them at start-up."""
import sys

dump, out = sys.argv[1], sys.argv[2]
want = set(int(x) for x in sys.argv[3].split(',')) if len(sys.argv) > 3 else None
lev, doff = {}, {}
for l in open(dump):
    f = l.split()
    if f[0] == 'L':
        d = dict(zip(f[2::2], map(int, f[3::2]))); lev[int(f[1])] = d
    elif f[0] == 'D':
        doff[(int(f[1]), int(f[2]))] = int(f[3])

o = ["// generated by gen.py from " + dump + " -- do not edit", ""]
gen = []
for t, d in sorted(lev.items()):
    if want is not None and t not in want: continue
    if not (d['on'] and d['vec'] and d['arena'] and d['nz'] == 1 and d['kt'] in (7, 8) and d['nr0'] == 0): continue
    kt, ntr, ndir, hs = d['kt'], d['ntr'], d['ndir'], d['hs']
    iend, dend = ntr - ndir, ntr
    V, W, LD = ('__m256i', 32, '_mm256_load_si256') if kt == 8 else ('__m128i', 16, '_mm_load_si128')
    AN, OR, TZ = (('_mm256_andnot_si256', '_mm256_or_si256', '_mm256_testz_si256') if kt == 8 else
                  ('_mm_andnot_si128', '_mm_or_si128', '_mm_testz_si128'))
    o.append(f"static inline __attribute__((always_inline)) int gen_L{t}(const uint16_t *S, const LV *L, u64 *w) {{   // kt {kt}, {iend} translate + {ndir} direct lanes")
    o.append("    const uint32_t *CVL = L->CVL, *CVH = L->CVH; const uint8_t *AR = L->AR, *DT = L->DT;")
    if kt == 8:
        o.append("    __m256i al = _mm256_load_si256((const __m256i *)L->allm); const __m256i io = _mm512_castsi512_si256(IOTA);")
        o.append(f"#define GT_{t}(I, B) do {{ const uint32_t s_ = S[I], e_ = CVL[(I) * 64 + (s_ & 63)] ^ CVH[(I) * {hs} + (s_ >> 6)]; "
                 "B = _mm256_load_si256((const __m256i *)(AR + (e_ >> 9))); "
                 "B = _mm256_permutexvar_epi8(_mm256_xor_si256(io, _mm256_set1_epi8((char)((e_ >> 3) & 31))), B); "
                 "B = _mm256_gf2p8affine_epi64_epi8(B, _mm256_set1_epi64x((long long)AFF[e_ & 7]), 0); } while (0)")
    else:
        o.append("    __m128i al = _mm_load_si128((const __m128i *)L->allm); const __m128i io = _mm512_castsi512_si128(IOTA);")
        o.append(f"#define GT_{t}(I, B) do {{ const uint32_t s_ = S[I], e_ = CVL[(I) * 64 + (s_ & 63)] ^ CVH[(I) * {hs} + (s_ >> 6)]; "
                 "B = _mm_load_si128((const __m128i *)(AR + (e_ >> 9))); "
                 "B = _mm_shuffle_epi8(B, _mm_xor_si128(io, _mm_set1_epi8((char)((e_ >> 3) & 15)))); "
                 "B = _mm_gf2p8affine_epi64_epi8(B, _mm_set1_epi64x((long long)AFF[e_ & 7]), 0); } while (0)")
    i = 0
    while i + 1 < iend:
        o.append(f"    {{ {V} B0, B1; GT_{t}({i}, B0); GT_{t}({i + 1}, B1); al = {AN}({OR}(B0, B1), al); if ({TZ}(al, al)) return 0; }}")
        i += 2
    if i < iend:
        o.append(f"    {{ {V} B0; GT_{t}({i}, B0); al = {AN}(B0, al); if ({TZ}(al, al)) return 0; }}")
        i += 1
    def dl(k):
        return f"{LD}((const {V} *)(DT + {doff[(t, k)]}u + (size_t)S[{k}] * {W}))"
    while i + 1 < dend:
        o.append(f"    al = {AN}({OR}({dl(i)}, {dl(i + 1)}), al); if ({TZ}(al, al)) return 0;")
        i += 2
    if i < dend:
        o.append(f"    al = {AN}({dl(i)}, al); if ({TZ}(al, al)) return 0;")
    o.append(f"    {'_mm256_store_si256((__m256i *)w, al)' if kt == 8 else '_mm_store_si128((__m128i *)w, al)'}; return 1;")
    o.append(f"#undef GT_{t}")
    o.append("}")
    gen.append((t, d))
o.append("static inline int gen_lanes(int t, const uint16_t *S, const LV *L, u64 *w) {")
o.append("    switch (t) {")
for t, d in gen:
    o.append(f"    case {t}: return gen_L{t}(S, L, w);")
o.append("    default: return -1;")
o.append("    }")
o.append("}")
o.append("static void gen_check(void) {   // the generated constants must describe this run's tables")
for t, d in gen:
    o.append(f"    {{ const LV *L = &LVL[{t}]; if (!L->on || !L->vec || !L->arena || L->nz != 1 || L->kt != {d['kt']} || L->nr0 != 0 || L->ntr != {d['ntr']} || L->ndir != {d['ndir']} || L->nc != {d['nc']} || L->hs != {d['hs']}) die(\"PKGGEN layout mismatch at level {t}\");")
    ks = sorted(k for (tt, k) in doff if tt == t)
    if ks:
        o.append(f"      static const uint32_t D{t}[] = {{{', '.join(str(doff[(t, k)]) for k in ks)}}};")
        o.append(f"      for (int k = 0; k < {len(ks)}; k++) if (L->DOFF[{ks[0]} + k] != D{t}[k]) die(\"PKGGEN direct-table offset mismatch at level {t}\"); }}")
    else:
        o.append("    }")
o.append(f"    fprintf(stderr, \"lwe11: generated lane loops for levels {' '.join(str(t) for t, _ in gen)}\\n\");")
o.append("}")
open(out, 'w').write('\n'.join(o) + '\n')
print(f"{out}: levels {[t for t, _ in gen]}")
